export type IconName = keyof typeof ICONS

export const icon = (name: IconName, className = 'ui-icon', strokeWidth = 2) => {
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg')
  svg.setAttribute('viewBox', '0 0 24 24')
  svg.setAttribute('fill', 'none')
  svg.setAttribute('stroke', 'currentColor')
  svg.setAttribute('stroke-width', String(strokeWidth))
  svg.setAttribute('stroke-linecap', 'round')
  svg.setAttribute('stroke-linejoin', 'round')
  svg.setAttribute('aria-hidden', 'true')
  svg.setAttribute('class', className)
  svg.innerHTML = ICONS[name]
  return svg
}

// The page's own controls name their icon (data-icon="x"): it is drawn once
// at start, in place of the character kept there as a fallback, or before
// the words of a control that has them.
// Any symbol a control drew as its icon: arrows, shapes, marks.
const GLYPHS = /^[\s\p{So}\p{Sm}‹›]*/u
export const hydrateIcons = (root: ParentNode = document) => {
  root.querySelectorAll<HTMLElement>('[data-icon]').forEach(element => {
    const name = element.dataset.icon as IconName
    if (!(name in ICONS) || element.querySelector(':scope > svg.ui-icon')) return
    const words = (element.textContent || '').replace(GLYPHS, '').replace(/[\s\p{So}\p{Sm}‹›]*$/u, '').trim()
    // data-icon-end: the icon after the words, as a "next" arrow reads.
    if ('iconEnd' in element.dataset) element.replaceChildren(...(words ? [words] : []), icon(name))
    else element.replaceChildren(icon(name), ...(words ? [words] : []))
  })
}
